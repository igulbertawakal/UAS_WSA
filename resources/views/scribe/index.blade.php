        <h1 id="introduction">Introduction</h1>
<p>RESTful API mini e-commerce untuk pengelolaan kategori dan produk.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost/UAS_WSA/public</code>
</aside>
<pre><code>API ini dibuat untuk proyek akhir Web Service Application. Login terlebih dahulu untuk mendapatkan bearer token, lalu gunakan token tersebut pada endpoint Categories dan Products.

&lt;aside&gt;Gunakan akun seed &lt;b&gt;admin@uas-wsa.test&lt;/b&gt; dengan password &lt;b&gt;password&lt;/b&gt; untuk pengujian.&lt;/aside&gt;</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {TOKEN_DARI_LOGIN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Ambil token dari respons endpoint <code>POST /api/login</code>, lalu kirim sebagai <code>Bearer TOKEN</code>.</p>

